//! An AI label: its fill, its edge, its sparkles and its word against the
//! board, the sizes, another word and no icon, a word longer than the room,
//! what tooling reads, that it takes no focus, and a theme's rules and
//! anatomy.

use std::sync::Arc;

use lurq::{
  app::{
    App,
    theme::{PaletteColor, ThemePalette},
  },
  components::{Column, Row},
  node::color::Color,
  ui::{AiLabel, AiLabelPart, AiLabelRenderer, AiLabelSize, AiLabelView, Button, icons},
};

use super::stage::Stage;

fn light(role: PaletteColor) -> Color {
  ThemePalette::light().get(role)
}

/// The character the theme's icon font draws `name` with.
fn glyph(name: &str) -> String {
  icons::ALL
    .iter()
    .find(|(held, _)| *held == name)
    .map(|(_, glyph)| glyph.to_string())
    .unwrap_or_else(|| panic!("no icon {name}"))
}

fn scene(label: impl Fn() -> AiLabel + Send + Sync + 'static) -> Stage {
  Stage::new(move |_| {
    Column::new()
      .padding(24.0)
      .child(Row::new().child(label().id("ai")))
      .into()
  })
}

#[test]
fn an_ai_label_is_sparkles_and_ai_in_the_info_color_on_its_muted_fill_with_an_edge() {
  let mut stage = scene(AiLabel::new);
  let (x, _, width, height) = stage.bounds("ai");
  assert_eq!(height, 22.0);
  assert_eq!(stage.fill_color("ai"), Some(light(PaletteColor::InfoMuted)));
  let fill = stage.fill("ai").unwrap();
  let radius = fill.border_radius.map_or(0.0, |radius| radius.top_left);
  assert!(radius > 0.0 && radius < 11.0, "the small radius, not a pill: {radius}");
  let edge = stage.border("ai").expect("an edge");
  let side = edge.border.and_then(|border| border.top).expect("a top side");
  assert_eq!((side.width, side.color), (1.0, light(PaletteColor::Info)));

  assert_eq!(stage.text("AI"), (light(PaletteColor::Info), 11.0));
  let sparkles = glyph(icons::SPARKLES);
  assert_eq!(stage.text(&sparkles), (light(PaletteColor::Info), 12.0));
  let icon = stage.text_quad(&sparkles).unwrap();
  let word = stage.text_quad("AI").unwrap();
  assert!((icon.x - x - 8.0).abs() < 0.01, "padded 8: {}", icon.x - x);
  assert!(
    (word.x - (icon.x + 12.0) - 4.0).abs() < 0.01,
    "4 after the sparkles: {}",
    word.x - (icon.x + 12.0)
  );
  assert!(
    (x + width - (word.x + word.width) - 8.0).abs() < 0.01,
    "padded 8 at its end: {}",
    x + width - (word.x + word.width)
  );
}

#[test]
fn the_sizes_are_18_22_and_26_high() {
  let mut stage = Stage::new(|_| {
    Column::new()
      .padding(24.0)
      .spacing(8.0)
      .child(Row::new().child(AiLabel::new().text("Small").size(AiLabelSize::Sm).id("sm")))
      .child(Row::new().child(AiLabel::new().text("Medium").id("md")))
      .child(Row::new().child(AiLabel::new().text("Large").size(AiLabelSize::Lg).id("lg")))
      .into()
  });
  for (id, word, height, size) in [
    ("sm", "Small", 18.0, 10.0),
    ("md", "Medium", 22.0, 11.0),
    ("lg", "Large", 26.0, 12.0),
  ] {
    assert_eq!(stage.bounds(id).3, height, "{id}");
    assert_eq!(stage.text(word).1, size, "{id}");
  }
}

#[test]
fn it_says_another_word_and_draws_no_icon_when_told() {
  let mut stage = scene(|| AiLabel::new().text("Draft").icon(None));
  assert!(stage.paints("Draft"));
  assert!(!stage.paints("AI"));
  assert!(!stage.paints(&glyph(icons::SPARKLES)), "no icon at all");
  let (x, ..) = stage.bounds("ai");
  let word = stage.text_quad("Draft").unwrap();
  assert!((word.x - x - 8.0).abs() < 0.01, "the word starts at the padding");

  let stage = scene(|| AiLabel::new().icon(icons::CHECK));
  assert!(stage.paints(&glyph(icons::CHECK)), "an icon of the app's own");
}

#[test]
fn a_word_longer_than_the_room_ends_in_an_ellipsis() {
  const WORDS: &str = "Generated by the assistant from the last twelve messages";
  let mut stage = Stage::new(|_| {
    Column::new()
      .size(400.0, 300.0)
      .child(
        Row::new()
          .id("room")
          .width(120.0)
          .child(AiLabel::new().text(WORDS).id("ai")),
      )
      .into()
  });
  let (room, _, room_width, _) = stage.bounds("room");
  let (x, _, width, _) = stage.bounds("ai");
  assert!(
    x >= room && x + width <= room + room_width + 0.5,
    "no wider than its room: {width}"
  );
  assert!(stage.text_quad(WORDS).is_none());
  let cut = stage.cut_text_quad(WORDS).expect("cut with an ellipsis");
  assert!(cut.x + cut.width <= x + width - 8.0 + 0.5, "inside its padding");
  assert!(stage.paints(&glyph(icons::SPARKLES)), "the icon keeps its room");
}

#[cfg(any(feature = "devtools", feature = "mcp"))]
#[test]
fn tooling_reads_a_note_called_by_its_word_or_its_label() {
  let mut stage = Stage::new(|_| {
    Column::new()
      .padding(24.0)
      .spacing(8.0)
      .child(Row::new().child(AiLabel::new().id("plain")))
      .child(
        Row::new().child(
          AiLabel::new()
            .text("Draft")
            .label("Drafted by the assistant")
            .id("named"),
        ),
      )
      .into()
  });
  let said = |stage: &mut Stage, id: &str, name: &str| {
    stage
      .tree
      .get_element_by_id_mut(id)
      .and_then(|element| element.description(name))
  };
  assert_eq!(said(&mut stage, "plain", "a11y_role").as_deref(), Some("note"));
  assert_eq!(said(&mut stage, "plain", "a11y_name").as_deref(), Some("AI"));
  assert_eq!(
    said(&mut stage, "named", "a11y_name").as_deref(),
    Some("Drafted by the assistant")
  );
}

#[test]
fn an_ai_label_takes_no_focus_and_tab_passes_it_by() {
  let mut stage = Stage::new(|_| {
    Column::new()
      .padding(24.0)
      .spacing(8.0)
      .child(Row::new().child(AiLabel::new().id("ai")))
      .child(Button::new("Regenerate").id("again"))
      .into()
  });
  stage.key("Tab");
  let focused = stage
    .tree
    .focused_element()
    .and_then(|element| element.id().map(str::to_owned));
  assert_eq!(focused.as_deref(), Some("again"));
}

#[test]
fn a_theme_restyles_an_ai_label_or_gives_it_another_anatomy() {
  let app = App::new();
  app.theme().patch_recipe::<AiLabel>(|rules| {
    rules
      .base(AiLabelPart::Root, |s| s.height(30.0).background(PaletteColor::Primary))
      .base(AiLabelPart::Label, |s| s.foreground(PaletteColor::PrimaryForeground))
  });
  let mut stage = Stage::in_app(app, |_| {
    Column::new()
      .padding(24.0)
      .child(Row::new().child(AiLabel::new().id("ai")))
      .into()
  });
  assert_eq!(stage.bounds("ai").3, 30.0);
  assert_eq!(stage.fill_color("ai"), Some(light(PaletteColor::Primary)));
  assert_eq!(stage.text("AI").0, light(PaletteColor::PrimaryForeground));

  let app = App::new();
  let renderer: AiLabelRenderer = Arc::new(|view: AiLabelView| {
    let part = view.part(AiLabelPart::Label);
    view.root().child(part.text(&format!("✦ {}", view.text))).into()
  });
  app.theme().set_renderer::<AiLabel>(renderer);
  let mut stage = Stage::in_app(app, |_| {
    Column::new()
      .padding(24.0)
      .child(Row::new().child(AiLabel::new().id("ai")))
      .into()
  });
  assert!(stage.paints("✦ AI"));
  assert_eq!(stage.fill_color("ai"), Some(light(PaletteColor::InfoMuted)));
}
