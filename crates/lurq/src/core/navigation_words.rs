#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn every_language_has_every_word_with_its_places() {
    for language in super::super::locale::LANGUAGES {
      let words = NavigationWords::for_language(language);
      for word in [&words.slide_of, &words.page_of, &words.step_of] {
        assert!(word.contains("{at}") && word.contains("{total}"), "{language}: {word}");
      }
      assert!(
        ["{first}", "{last}", "{total}"]
          .iter()
          .all(|place| words.range_of.contains(place))
      );
      assert!(words.hide_app.contains("{app}"), "{language}");
      assert!(
        words.steps_done.forms().iter().all(|form| form.contains("{count}")),
        "{language}"
      );
      assert!(
        words.hidden_tabs.forms().iter().all(|form| form.contains("{count}")),
        "{language}"
      );
      assert!(
        words.search_tabs.forms().iter().all(|form| form.contains("{count}")),
        "{language}"
      );
      assert!(words.no_tab_matches.contains("{query}"), "{language}");
      assert!(!words.main.is_empty() && !words.show_all.is_empty(), "{language}");
    }
    assert_eq!(NavigationWords::for_language("xx"), NavigationWords::english());
  }
}
