//! What the ways about an app say by themselves: windows and their panels, tabs, bars and menus of the app, pages,
//! slides and pictures turned through, steps gone through, and notifications. A part of the app's
//! [`Locale`](super::Locale).

use std::sync::Arc;

use super::Plural;

/// What the ways about an app say by themselves, in a locale's words. Every field is the app's to replace.
///
/// ```
/// use lurq::core::{Locale, fill};
///
/// let locale = Locale::for_tag("de");
/// assert_eq!(&*locale.navigation.next_page, "Nächste Seite");
/// assert_eq!(fill(&locale.navigation.page_of, &[("at", "2"), ("total", "9")]), "Seite 2 von 9");
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NavigationWords {
  /// What the main navigation of an app is called, and the button that opens it on a narrow window.
  pub main: Arc<str>,
  pub menu: Arc<str>,
  /// What a breadcrumb and a path are called, and the button of the steps folded away.
  pub breadcrumb: Arc<str>,
  pub path: Arc<str>,
  pub show_hidden_steps: Arc<str>,
  /// What a sidebar and a group of it with no label are called, and its buttons.
  pub sidebar: Arc<str>,
  pub group: Arc<str>,
  pub collapse_sidebar: Arc<str>,
  pub expand_sidebar: Arc<str>,
  pub open_sidebar: Arc<str>,
  pub close_sidebar: Arc<str>,
  /// The buttons of a window's title bar, and of a panel of a dock layout.
  pub minimize: Arc<str>,
  pub maximize: Arc<str>,
  pub restore: Arc<str>,
  /// The buttons of tabs: one that adds a tab, one that shows those that do not fit, one that opens a menu of
  /// them, and the arrows that scroll them.
  pub new_tab: Arc<str>,
  pub show_hidden_tabs: Arc<str>,
  pub more_tabs: Arc<str>,
  /// How many tabs a button holds that did not fit: "3 hidden tabs".
  pub hidden_tabs: Plural,
  /// The list of every open tab a strip's button opens: what it is called, what its search field says while it is
  /// empty ("Search 12 open tabs"), what it says where nothing matches (`{query}`, what was typed), and what a row
  /// of a tab not in the strip is described by.
  pub open_tabs: Arc<str>,
  pub search_tabs: Plural,
  pub no_tab_matches: Arc<str>,
  pub not_in_strip: Arc<str>,
  pub scroll_back: Arc<str>,
  pub scroll_on: Arc<str>,
  /// What a dock layout is called, and what is done with its panels.
  pub dock_layout: Arc<str>,
  pub float: Arc<str>,
  pub hide: Arc<str>,
  pub put_back: Arc<str>,
  pub move_left: Arc<str>,
  pub move_right: Arc<str>,
  pub move_top: Arc<str>,
  pub move_bottom: Arc<str>,
  pub hidden_panels: Arc<str>,
  /// The handles of a floating panel, and what its keys do with them.
  pub move_panel: Arc<str>,
  pub resize: Arc<str>,
  pub collapse: Arc<str>,
  pub move_hint: Arc<str>,
  pub resize_hint: Arc<str>,
  pub back_to_top: Arc<str>,
  /// The title of a table of contents.
  pub on_this_page: Arc<str>,
  /// What a carousel is called, what kind of thing it and a slide of it are to what reads the tree, its arrows,
  /// and a slide with `{at}` and `{total}`.
  pub carousel: Arc<str>,
  pub carousel_role: Arc<str>,
  pub slide_role: Arc<str>,
  pub previous_slide: Arc<str>,
  pub next_slide: Arc<str>,
  pub slide_of: Arc<str>,
  /// What a lightbox is called, and its buttons.
  pub pictures: Arc<str>,
  pub previous_picture: Arc<str>,
  pub next_picture: Arc<str>,
  pub zoom_in: Arc<str>,
  pub zoom_out: Arc<str>,
  pub fit_to_window: Arc<str>,
  /// What a pagination is called, its arrows, a page by its number, and what it says of where it is: a page with
  /// `{at}` and `{total}`, the rows of a page with `{first}`, `{last}` and `{total}`.
  pub pagination: Arc<str>,
  pub previous_page: Arc<str>,
  pub next_page: Arc<str>,
  pub page: Arc<str>,
  pub page_of: Arc<str>,
  pub range_of: Arc<str>,
  /// A step of steps, with `{at}` and `{total}`, and what it is: done, the current one, to come, wrong.
  pub step_of: Arc<str>,
  pub step_done: Arc<str>,
  pub step_current: Arc<str>,
  pub step_to_come: Arc<str>,
  pub step_error: Arc<str>,
  /// Steps all gone through: "4 of 4 steps done".
  pub steps_done: Plural,
  /// A notification center: its title, what it says empty, and its buttons; and a notification not yet read.
  pub notifications: Arc<str>,
  pub no_notifications: Arc<str>,
  pub mark_all_read: Arc<str>,
  pub clear_all: Arc<str>,
  pub view_all: Arc<str>,
  pub unread: Arc<str>,
  /// What a command bar is called, and its button of the commands that do not fit.
  pub commands: Arc<str>,
  pub more_commands: Arc<str>,
  /// The buttons of an action bar.
  pub clear_selection: Arc<str>,
  pub more_actions: Arc<str>,
  /// The menu of the app on a Mac: its name until the app gives one, its last item, and what the system puts in
  /// it, with `{app}` for the app's name.
  pub application: Arc<str>,
  pub quit: Arc<str>,
  pub services: Arc<str>,
  pub hide_app: Arc<str>,
  pub hide_others: Arc<str>,
  pub show_all: Arc<str>,
  /// The Edit menu lurq puts in the bar of an app on a Mac, and the item of the system's characters in it.
  pub edit: Arc<str>,
  pub emoji_and_symbols: Arc<str>,
  /// Select All in the Edit menu, as the system writes an item of its menus.
  pub select_all: Arc<str>,
}

