//! What the tools of writing say by themselves: finding and replacing, a rich text editor's tools, a block of code,
//! a command palette, and what a Markdown document calls its notes. A part of the app's [`Locale`](super::Locale).

use std::sync::Arc;

use super::Plural;

/// What the tools of writing say by themselves, in a locale's words. Every field is the app's to replace.
///
/// ```
/// use lurq::core::Locale;
///
/// let locale = Locale::for_tag("es");
/// assert_eq!(&*locale.editing.replace_all, "Reemplazar todo");
/// assert_eq!(locale.count(&locale.editing.words, 1), "1 palabra");
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EditingWords {
  /// A find bar: what it is called and says empty, its fields, its buttons and its options.
  pub find: Arc<str>,
  pub replace: Arc<str>,
  pub previous_match: Arc<str>,
  pub next_match: Arc<str>,
  pub match_case: Arc<str>,
  pub match_whole_word: Arc<str>,
  pub use_regex: Arc<str>,
  pub replace_all: Arc<str>,
  pub toggle_replace: Arc<str>,
  pub search_options: Arc<str>,
  /// A rich text editor's toolbar, its menu of the kinds of paragraph, and its tools. A heading has `{level}`.
  pub formatting: Arc<str>,
  pub text_style: Arc<str>,
  pub paragraph: Arc<str>,
  pub heading: Arc<str>,
  pub code_block: Arc<str>,
  pub bold: Arc<str>,
  pub italic: Arc<str>,
  pub underline: Arc<str>,
  pub strikethrough: Arc<str>,
  pub bulleted_list: Arc<str>,
  pub numbered_list: Arc<str>,
  pub quote: Arc<str>,
  /// Code in a line of text, and what a block of code is called with no title and no language.
  pub code: Arc<str>,
  pub link: Arc<str>,
  pub image: Arc<str>,
  pub undo: Arc<str>,
  pub redo: Arc<str>,
  /// The menu of editing commands a finger opens, over text selected by touch or under three fingers' tap; with
  /// `undo`, `redo` and `common.select_all`.
  pub cut: Arc<str>,
  pub copy: Arc<str>,
  pub paste: Arc<str>,
  /// The field of a link's address, the button that takes the link away, and what the editor says of its
  /// shortcuts.
  pub paste_link: Arc<str>,
  pub remove_link: Arc<str>,
  pub markdown_shortcuts: Arc<str>,
  /// The count of an editor's words: "120 words".
  pub words: Plural,
  /// The button of a block of code, and what it says once the code is copied.
  pub copy_code: Arc<str>,
  pub copied: Arc<str>,
  /// What the button of a block of code says where the clipboard did not take the code.
  pub copy_failed: Arc<str>,
  /// What a command palette says until something is typed, and the hints of its keys.
  pub command_placeholder: Arc<str>,
  pub to_move: Arc<str>,
  pub to_run: Arc<str>,
  pub to_close: Arc<str>,
  /// The titles of a Markdown document's notes (`> [!NOTE]`).
  pub note: Arc<str>,
  pub tip: Arc<str>,
  pub important: Arc<str>,
  pub warning: Arc<str>,
  pub caution: Arc<str>,
  /// The way back from a footnote, with `{number}` for its reference.
  pub back_to_reference: Arc<str>,
}

