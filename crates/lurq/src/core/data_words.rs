//! What tables, lists and charts say by themselves: a table's counts of rows, its menus of a column, its filters,
//! its export and its sums, and what a chart is called and reads out. A part of the app's [`Locale`](super::Locale).

use std::sync::Arc;

use super::Plural;

/// What tables, lists and charts say by themselves, in a locale's words. Every field is the app's to replace.
///
/// ```
/// use lurq::core::Locale;
///
/// let locale = Locale::for_tag("uk");
/// assert_eq!(&*locale.data.sort_ascending, "Сортувати за зростанням");
/// assert_eq!(locale.count(&locale.data.rows, 22), "22 рядки");
/// assert_eq!(locale.count(&locale.data.rows, 25), "25 рядків");
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DataWords {
  /// The title of a table's column of actions.
  pub actions_column: Arc<str>,
  /// What a table says of rows that failed to load, and with none.
  pub rows_failed: Arc<str>,
  pub no_rows: Arc<str>,
  pub select_row: Arc<str>,
  pub select_none: Arc<str>,
  /// How many rows a table has: "12 rows".
  pub rows: Plural,
  /// How many of them are shown, with `{shown}`, the form by `{count}`: "5 of 12 rows".
  pub shown_rows: Plural,
  /// How many of them are chosen, with `{selected}`, the form by `{count}`: "2 of 12 rows selected".
  pub selected_rows: Plural,
  /// What the controls of a column are called, with `{column}` for its title.
  pub column_menu: Arc<str>,
  pub resize_column: Arc<str>,
  pub sort_by: Arc<str>,
  /// The menu of a column, and of the columns shown.
  pub columns: Arc<str>,
  pub sort_ascending: Arc<str>,
  pub sort_descending: Arc<str>,
  pub clear_sort: Arc<str>,
  pub pin_start: Arc<str>,
  pub pin_end: Arc<str>,
  pub unpin: Arc<str>,
  pub size_to_fit: Arc<str>,
  pub hide_column: Arc<str>,
  pub show_all_columns: Arc<str>,
  /// The menu of what a table is exported as.
  pub export: Arc<str>,
  pub shown_csv: Arc<str>,
  pub shown_tsv: Arc<str>,
  pub selected_csv: Arc<str>,
  pub selected_tsv: Arc<str>,
  /// The bar of a table's tools, and how close its rows are.
  pub grid_tools: Arc<str>,
  pub search_rows: Arc<str>,
  pub filter: Arc<str>,
  pub density: Arc<str>,
  pub comfortable: Arc<str>,
  pub default: Arc<str>,
  pub compact: Arc<str>,
  /// A filter of a range said in a tag, with `{from}` and `{to}`.
  pub from_to: Arc<str>,
  pub from_only: Arc<str>,
  pub to_only: Arc<str>,
  /// The menu of a column's filter.
  pub filter_placeholder: Arc<str>,
  pub clear_filter: Arc<str>,
  pub clear_all_filters: Arc<str>,
  pub contains: Arc<str>,
  pub starts_with: Arc<str>,
  pub equals: Arc<str>,
  pub at_least: Arc<str>,
  pub at_most: Arc<str>,
  pub from: Arc<str>,
  pub to: Arc<str>,
  pub all: Arc<str>,
  /// A filter of several values said in a tag: "3 values".
  pub values: Plural,
  /// What the row of a table's sums is called, and each sum.
  pub summary: Arc<str>,
  pub sum: Arc<str>,
  pub average: Arc<str>,
  pub count: Arc<str>,
  pub min: Arc<str>,
  pub max: Arc<str>,
  /// What a chart and its legend are called, what kind of thing a chart is to what reads the tree, and what one
  /// with nothing says.
  pub chart: Arc<str>,
  pub chart_role: Arc<str>,
  pub legend: Arc<str>,
  pub no_data: Arc<str>,
  /// A bar of a series of several, with `{name}` for its category and `{number}` for the series.
  pub series: Arc<str>,
  /// The ends of a heatmap's scale, the scale with `{less}` and `{more}`, and a cell with no value.
  pub less: Arc<str>,
  pub more: Arc<str>,
  pub scale: Arc<str>,
  pub no_value: Arc<str>,
  /// What a sparkline reads out, with `{least}`, `{most}` and `{last}`: "12 values from 3 to 40, the last 18".
  pub values_summary: Plural,
}

